export interface PixelRun {
  /** Lit cells as [column, row] in text-pixel space, origin top-left. */
  cells: [number, number][];
  /** Width in text pixels, including tracking. */
  width: number;
  /** Height in text pixels. */
  height: number;
}

/** Rasterises a single line. Unknown glyphs advance by one glyph width. */
export function layoutLine(text: string): PixelRun {
  const cells: [number, number][] = [];
  let x = 0;
  const upper = text.toUpperCase();

  for (const ch of upper) {
    if (ch === " ") {
      x += 3 + TRACKING;
      continue;
    }
    const glyph = G[ch];
    if (glyph) {
      for (let row = 0; row < GLYPH_H; row += 1) {
        const bits = glyph[row];
        for (let col = 0; col < GLYPH_W; col += 1) {
          if (bits[col] === "1") cells.push([x + col, row]);
        }
      }
    }
    x += GLYPH_W + TRACKING;
  }

  return { cells, width: Math.max(0, x - TRACKING), height: GLYPH_H };
}
